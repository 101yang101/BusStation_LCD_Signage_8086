void DelayTime()
{
	unsigned char i;
	unsigned int j;
	for (i = 0; i < 1; i++)
	{
		for (j = 0; j < 0x8fff; j++)
		{;}
	}
}

u8 SPDelayTime()
{
	unsigned char i;
	unsigned int j;
	for (i = 0; i < 1; i++)
	{
		for (j = 0; j < 0x00ff; j++)
			if (AllKey()) {
				return 1;
			}
	}
	return 0;
}

